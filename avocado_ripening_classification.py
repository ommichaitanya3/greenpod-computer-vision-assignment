IMAGE_SIZE = (128, 128)
CLASSES = ["blackspot", "canker", "fresh", "grenning"]

def extract_features(image_path):
    image = cv2.imread(image_path)

    if image is None:
        return None

    image = cv2.resize(image, IMAGE_SIZE)

    # Color features: CIELAB
    lab = cv2.cvtColor(image, cv2.COLOR_BGR2LAB)
    color_features = []

    for channel in cv2.split(lab):
        hist = cv2.calcHist(
            [channel], [0], None, [16], [0, 256]
        )
        hist = cv2.normalize(hist, hist).flatten()
        color_features.extend(hist)

    # Texture features: Local Binary Patterns
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    lbp = local_binary_pattern(gray, P=8, R=1, method="uniform")

    texture_hist, _ = np.histogram(
        lbp.ravel(),
        bins=np.arange(0, 11),
        range=(0, 10)
    )

    texture_hist = texture_hist.astype("float32")
    texture_hist /= (texture_hist.sum() + 1e-7)

    return np.concatenate([
        np.array(color_features, dtype="float32"),
        texture_hist
    ])

def load_split(split):
    features, labels = [], []
    split_path = os.path.join(DATASET_PATH, split)

    for label in CLASSES:
        folder = os.path.join(split_path, label)

        for filename in os.listdir(folder):
            if filename.lower().endswith((".jpg", ".jpeg", ".png")):
                path = os.path.join(folder, filename)
                vector = extract_features(path)

                if vector is not None:
                    features.append(vector)
                    labels.append(label)

    return np.array(features), np.array(labels)

